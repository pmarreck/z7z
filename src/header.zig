test "header parse: TV-A valid" {
    const hdr = try parse(&tv_a);
    try std.testing.expectEqual(@as(u8, 0), hdr.major_version);
    try std.testing.expectEqual(@as(u8, 4), hdr.minor_version);
    try std.testing.expectEqual(@as(u64, 6), hdr.next_header_offset);
    try std.testing.expectEqual(@as(u64, 0x4A), hdr.next_header_size);
    try std.testing.expectEqual(@as(u32, 0xD547C7DD), hdr.next_header_crc);
}

test "header parse: TV-B valid" {
    const hdr = try parse(&tv_b);
    try std.testing.expectEqual(@as(u8, 0), hdr.major_version);
    try std.testing.expectEqual(@as(u64, 0x0A), hdr.next_header_offset);
    try std.testing.expectEqual(@as(u64, 0x5A), hdr.next_header_size);
}

test "header parse: TV-C valid (encrypted header)" {
    const hdr = try parse(&tv_c);
    try std.testing.expectEqual(@as(u8, 0), hdr.major_version);
    try std.testing.expectEqual(@as(u64, 0x80), hdr.next_header_offset);
    try std.testing.expectEqual(@as(u64, 0x2E), hdr.next_header_size);
}

test "header parse: bad signature → NotArchive" {
    var bad = tv_a;
    bad[0] = 0x00; // corrupt signature
    try std.testing.expectError(ParseError.NotArchive, parse(&bad));
}

test "header parse: bad StartHeaderCRC → ChecksumError" {
    var bad = tv_a;
    bad[8] = 0x00; // corrupt CRC
    try std.testing.expectError(ParseError.ChecksumError, parse(&bad));
}

test "header parse: truncated input" {
    try std.testing.expectError(ParseError.TruncatedInput, parse(tv_a[0..20]));
}

test "header encode: roundtrip with TV-A" {
    const original = try parse(&tv_a);
    const encoded = encode(original);
    const reparsed = try parse(&encoded);

    try std.testing.expectEqual(original.major_version, reparsed.major_version);
    try std.testing.expectEqual(original.minor_version, reparsed.minor_version);
    try std.testing.expectEqual(original.next_header_offset, reparsed.next_header_offset);
    try std.testing.expectEqual(original.next_header_size, reparsed.next_header_size);
    try std.testing.expectEqual(original.next_header_crc, reparsed.next_header_crc);
}

test "header encode: bytes match TV-A header" {
    const original = try parse(&tv_a);
    const encoded = encode(original);
    // First 32 bytes should match exactly
    try std.testing.expectEqualSlices(u8, tv_a[0..HEADER_SIZE], &encoded);
}

test "header: NextHeaderCRC validates next-header region in TV-A" {
    const hdr = try parse(&tv_a);
    // Next-header region starts at offset 0x20 + next_header_offset
    const nh_start = HEADER_SIZE + hdr.next_header_offset;
    const nh_end = nh_start + hdr.next_header_size;
    const next_header_bytes = tv_a[nh_start..nh_end];
    const computed_crc = crc32.hash(next_header_bytes);
    try std.testing.expectEqual(hdr.next_header_crc, computed_crc);
}
