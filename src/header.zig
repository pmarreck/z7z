//! 7z Signature Header — the fixed 32-byte header at offset 0.
//!
//! Layout (spec section 1.1):
//!   [0x00..0x06) Signature: 37 7A BC AF 27 1C
//!   [0x06]       Major version (MUST be 0)
//!   [0x07]       Minor version
//!   [0x08..0x0C) StartHeaderCRC — CRC32 of bytes [0x0C..0x20)
//!   [0x0C..0x14) NextHeaderOffset (REAL_UINT64, LE)
//!   [0x14..0x1C) NextHeaderSize (REAL_UINT64, LE)
//!   [0x1C..0x20) NextHeaderCRC — CRC32 of next-header region

const std = @import("std");
const crc32 = @import("crc32.zig");

pub const HEADER_SIZE: usize = 32;
pub const SIGNATURE = [6]u8{ 0x37, 0x7A, 0xBC, 0xAF, 0x27, 0x1C };

pub const ParseError = error{
    NotArchive,
    ChecksumError,
    TruncatedInput,
};

pub const SignatureHeader = struct {
    major_version: u8,
    minor_version: u8,
    next_header_offset: u64,
    next_header_size: u64,
    next_header_crc: u32,

    /// Total archive bytes from start that the next-header region occupies.
    pub fn nextHeaderAbsoluteOffset(self: SignatureHeader) u64 {
        return HEADER_SIZE + self.next_header_offset;
    }
};

/// Parse and validate a 32-byte signature header.
pub fn parse(data: []const u8) ParseError!SignatureHeader {
    if (data.len < HEADER_SIZE) return ParseError.TruncatedInput;

    // Check signature
    if (!std.mem.eql(u8, data[0..6], &SIGNATURE)) return ParseError.NotArchive;

    // Check major version
    const major = data[6];
    if (major != 0) return ParseError.NotArchive;

    // Validate StartHeaderCRC (covers bytes 0x0C..0x1F)
    const stored_crc = std.mem.readInt(u32, data[0x08..0x0C], .little);
    const computed_crc = crc32.hash(data[0x0C..HEADER_SIZE]);
    if (stored_crc != computed_crc) return ParseError.ChecksumError;

    return .{
        .major_version = major,
        .minor_version = data[7],
        .next_header_offset = std.mem.readInt(u64, data[0x0C..0x14], .little),
        .next_header_size = std.mem.readInt(u64, data[0x14..0x1C], .little),
        .next_header_crc = std.mem.readInt(u32, data[0x1C..0x20], .little),
    };
}

/// Encode a SignatureHeader into a 32-byte buffer.
pub fn encode(hdr: SignatureHeader) [HEADER_SIZE]u8 {
    var buf: [HEADER_SIZE]u8 = undefined;

    // Signature
    @memcpy(buf[0..6], &SIGNATURE);

    // Version
    buf[6] = hdr.major_version;
    buf[7] = hdr.minor_version;

    // Payload (bytes 0x0C..0x1F): NextHeaderOffset, NextHeaderSize, NextHeaderCRC
    std.mem.writeInt(u64, buf[0x0C..0x14], hdr.next_header_offset, .little);
    std.mem.writeInt(u64, buf[0x14..0x1C], hdr.next_header_size, .little);
    std.mem.writeInt(u32, buf[0x1C..0x20], hdr.next_header_crc, .little);

    // StartHeaderCRC over bytes 0x0C..0x1F
    const start_crc = crc32.hash(buf[0x0C..HEADER_SIZE]);
    std.mem.writeInt(u32, buf[0x08..0x0C], start_crc, .little);

    return buf;
}

